// Combines every migration plus seed.sql into supabase/setup.sql, a single file you can
// paste into the Supabase dashboard SQL editor (no CLI needed). Run: npm run db:setup-sql
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const migrations = join(root, 'supabase/migrations');
const parts = readdirSync(migrations)
  .filter((f) => f.endsWith('.sql'))
  .sort()
  .map((f) => `-- ===== migrations/${f} =====\n${readFileSync(join(migrations, f), 'utf8')}`);
parts.push(`-- ===== seed.sql =====\n${readFileSync(join(root, 'supabase/seed.sql'), 'utf8')}`);
writeFileSync(
  join(root, 'supabase/setup.sql'),
  `-- GENERATED by \`npm run db:setup-sql\`. Paste into Supabase → SQL Editor → Run, on a NEW project.\n\n${parts.join('\n\n')}`,
);
console.log('Wrote supabase/setup.sql');
