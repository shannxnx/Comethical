// Generates supabase/seed.sql from the TypeScript seed data.
// Requires Node 22.18+ / 23.6+ (native TypeScript type stripping).
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { DEFAULT_CATEGORIES } from '../src/core/categories.ts';
import { SEED_SCENARIOS } from '../src/data/seed-scenarios.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const q = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`);
const arr = (values) => `array[${values.map(q).join(', ')}]::text[]`;

const lines = [
  '-- GENERATED by `npm run seed:sql` from src/core/categories.ts and src/data/seed-scenarios.ts.',
  '-- Do not edit by hand. Seed scenarios are hand-written and pre-approved.',
  '',
  'insert into public.categories (id, name, description, icon, color, active, sort_order) values',
  DEFAULT_CATEGORIES.map(
    (c, i) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.description)}, ${q(c.icon)}, ${q(c.color)}, ${c.active}, ${i})`,
  ).join(',\n'),
  'on conflict (id) do update set name = excluded.name, description = excluded.description, icon = excluded.icon,',
  '  color = excluded.color, active = excluded.active, sort_order = excluded.sort_order;',
  '',
  'insert into public.scenarios (id, category_id, scenario_text, correct_answer, explanation, ethical_principles,',
  '  recommended_action, difficulty_score, difficulty_reasoning, learning_objective, generation_source, approval_status) values',
  SEED_SCENARIOS.map(
    (s) =>
      `  (md5(${q(s.id)})::uuid, ${q(s.categoryId)}, ${q(s.text)}, ${q(s.correctAnswer)}, ${q(s.explanation)}, ` +
      `${arr(s.ethicalPrinciples)}, ${q(s.recommendedAction)}, ${s.difficulty}, ${q(s.difficultyReasoning)}, ` +
      `${q(s.learningObjective)}, 'seed', 'approved')`,
  ).join(',\n'),
  'on conflict (id) do nothing;',
  '',
];

writeFileSync(resolve(root, 'supabase/seed.sql'), lines.join('\n'));
console.log(`Wrote supabase/seed.sql: ${DEFAULT_CATEGORIES.length} categories, ${SEED_SCENARIOS.length} scenarios.`);
